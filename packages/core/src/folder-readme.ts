// A folder's guide (views/folder-guide.ts) as its README.md: the generated part between
// markers, everything else a person's.
import type { FolderGuide } from "@runshape/views";

export const README_BEGIN = "<!-- runshape:begin";
export const README_END = "<!-- runshape:end -->";

export interface GuideContext {
  style: string;
  /** How many rules runshape.json has: none means every zone was inferred. */
  rules: number;
}

/**
 * The generated part, markers included. Names only, from the recording; nothing a model wrote.
 * No commit and no counts in it: it's committed with the code, and either would change it on
 * every commit and every new test, burying the changes that matter.
 */
export function folderGuideMarkdown(guide: FolderGuide, context: GuideContext): string {
  const where = guide.folder === "" ? "the project's root" : guide.folder;
  const out = [
    `${README_BEGIN} (generated by \`npm run runshape -- readmes\` from what the tests run; edits between these markers are replaced) -->`,
    `## What's in ${where}`,
    "",
    `${zoneSentence(guide)} Drawn ${context.style}${context.rules === 0 ? ", every zone inferred from what the code did (no runshape.json rules)" : `, from ${context.rules} runshape.json rule${context.rules === 1 ? "" : "s"} and what the code did`}.`,
    "",
    "| File | Zone | Classes | Used from other files |",
    "|---|---|---|---|",
    ...guide.files.map((file) => {
      const name = code(file.name);
      if (file.declarationsOnly) return `| ${name} | — | | no functions of its own (types, re-exports, or a script's top-level code) |`;
      if (!file.seen) return `| ${name} | not seen running | | ${file.functionCount > 0 ? `none of its ${file.functionCount} functions ran` : "not loaded by the tests"} |`;
      const used = file.functions.map((f) => code(f.name)).join(", ") || "—";
      return `| ${name} | ${file.zones.map((z) => guide.zoneNames[z] ?? z).join(", ") || "—"} | ${file.classes.map((c) => code(c.name)).join(", ") || "—"} | ${used} |`;
    }),
    "",
  ];
  if (guide.questions.length > 0) out.push("### Questions this raises", "", ...guide.questions.map((q) => `- ${q}`), "");
  out.push(README_END, "");
  return out.join("\n");
}

/** "Mostly Core" only when most of its files are; otherwise the largest share, said as such. */
function zoneSentence(guide: FolderGuide): string {
  if (guide.zone === null) return "None of its code was placed in a zone.";
  const placed = guide.files.filter((f) => f.zones.length > 0);
  const inZone = placed.filter((f) => f.zones.includes(guide.zone!)).length;
  return inZone * 2 > placed.length
    ? `Mostly **${guide.zoneName}** code.`
    : `Mixed: **${guide.zoneName}** is the largest share (${inZone} of ${placed.length} files).`;
}

export interface MergedReadme {
  status: "created" | "updated" | "unchanged" | "skipped";
  text: string;
}

/**
 * The guide put into a folder's README: a new one gets a title and a line for a person; one with
 * the markers has only the part between them replaced; one without them is someone's own, and
 * is left alone.
 */
export function mergeIntoReadme(existing: string | null, block: string, folder: string): MergedReadme {
  if (existing === null) {
    const title = folder === "" ? "This project" : folder;
    return { status: "created", text: `# ${title}\n\n_What this folder is for, in a sentence or two: yours to write; runshape keeps the part below._\n\n${block}` };
  }
  // Markers count only as lines of their own, and only one pair: a README that writes about them
  // in its text, or has two blocks, isn't guessed at.
  const lines = existing.split("\n");
  const begins = lines.flatMap((line, i) => (/^<!-- runshape:begin\b.*-->\s*$/.test(line) ? [i] : []));
  const ends = lines.flatMap((line, i) => (/^<!-- runshape:end -->\s*$/.test(line) ? [i] : []));
  if (begins.length !== 1 || ends.length !== 1 || ends[0]! < begins[0]!) return { status: "skipped", text: existing };
  const text = [...lines.slice(0, begins[0]), block.replace(/\n$/, ""), ...lines.slice(ends[0]! + 1)].join("\n");
  return { status: text === existing ? "unchanged" : "updated", text };
}

/**
 * A name in a table cell: a code span, so `__init__.py` isn't read as bold; a "|" escaped (it
 * would end the cell even inside one), a backtick-holding name fenced with two.
 */
function code(name: string): string {
  const text = name.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
  return text.includes("`") ? `\`\` ${text} \`\`` : `\`${text}\``;
}
