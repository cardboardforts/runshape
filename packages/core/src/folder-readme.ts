// A folder's guide (views/folder-guide.ts) as its README.md: the generated part between
// markers, everything else a person's.
import type { FolderGuide } from "@runshape/views";

export const README_BEGIN = "<!-- runshape:begin";
export const README_END = "<!-- runshape:end -->";

export interface GuideContext {
  /** The commit the recording was made at: the guide is true of that. */
  commit: string;
  style: string;
  /** How many rules runshape.json has: none means every zone was inferred. */
  rules: number;
}

/** The generated part, markers included. Names only, from the recording; nothing a model wrote. */
export function folderGuideMarkdown(guide: FolderGuide, context: GuideContext): string {
  const where = guide.folder === "" ? "the project's root" : guide.folder;
  const out = [
    `${README_BEGIN} (generated by \`npm run runshape -- readmes\` from the recording of ${context.commit.slice(0, 12)}; edits between these markers are replaced) -->`,
    `## What's in ${where}`,
    "",
    guide.zoneName === null
      ? "None of its code was placed in a zone."
      : `Mostly **${guide.zoneName}** code, drawn ${context.style}${context.rules === 0 ? ": every zone inferred from what the code did, no runshape.json rules" : `, by ${context.rules} runshape.json rule${context.rules === 1 ? "" : "s"} and what the code did`}.`,
    "",
    "| File | Zone | Classes | Entry points (calls from outside the file), of its functions |",
    "|---|---|---|---|",
    ...guide.files.map((file) =>
      file.seen
        ? `| ${cell(file.name)} | ${file.zones.map((z) => cell(guide.zoneNames[z] ?? z)).join(", ") || "—"} | ${file.classes.map((c) => cell(c.name)).join(", ") || "—"} | ${file.functions.map((f) => `${cell(f.name)} ×${f.calls}`).join(", ") || "—"} (of ${file.functionCount}) |`
        : file.declarationsOnly
          ? `| ${cell(file.name)} | — | | no functions of its own (types, re-exports, or a script's top-level code) |`
          : `| ${cell(file.name)} | not seen running | | ${file.functionCount > 0 ? `(${file.functionCount} functions)` : ""} |`,
    ),
    "",
  ];
  if (guide.questions.length > 0) out.push("### Questions this raises", "", ...guide.questions.map((q) => `- ${q}`), "");
  out.push(README_END, "");
  return out.join("\n");
}

export interface MergedReadme {
  status: "created" | "updated" | "unchanged" | "skipped";
  text: string;
}

/**
 * The guide put into a folder's README: a new one gets a title and a line for a person; one with
 * the markers has only the part between them replaced; one without them is someone's own, and
 * is left alone.
 */
export function mergeIntoReadme(existing: string | null, block: string, folder: string): MergedReadme {
  if (existing === null) {
    const title = folder === "" ? "This project" : folder;
    return { status: "created", text: `# ${title}\n\n_What this folder is for, in a sentence or two: yours to write; runshape keeps the part below._\n\n${block}` };
  }
  const begin = existing.indexOf(README_BEGIN);
  const end = existing.indexOf(README_END, begin);
  if (begin === -1 || end === -1) return { status: "skipped", text: existing };
  const after = existing.slice(end + README_END.length).replace(/^\n/, "");
  const text = `${existing.slice(0, begin)}${block}${after}`;
  return { status: text === existing ? "unchanged" : "updated", text };
}

/** A table cell can't hold a "|" or a line break. */
function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}
