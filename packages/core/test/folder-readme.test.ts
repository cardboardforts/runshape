/**
 * A folder's guide as its README: the generated part between markers, replaced each time; the
 * rest (what the folder is for, in a person's words) never touched. A README with no markers is
 * someone's own: it's left alone.
 */
import { describe, expect, test } from "vitest";

import { loadLatestRun } from "@runshape/trace";
import { ZoneRules } from "@runshape/architecture";
import { buildFolderGuides, buildPlacements } from "@runshape/views";
import { folderGuideMarkdown, mergeIntoReadme } from "../src/folder-readme";
import { fixtureFiles } from "../../trace/test/fixtures";

async function webGuide() {
  const run = await loadLatestRun(fixtureFiles("go-shop"));
  const snapshot = buildPlacements(run, ZoneRules.none());
  return { guide: buildFolderGuides(run, snapshot, [...new Set(run.catalog.map((fn) => fn.file))]).find((g) => g.folder === "internal/web")!, snapshot };
}

describe("folderGuideMarkdown", () => {
  test("the folder's zone, a table of its files, and the questions it raises", async () => {
    const { guide, snapshot } = await webGuide();

    expect(folderGuideMarkdown(guide, { commit: "0123456789abcdef", style: snapshot.style, rules: snapshot.rules.length })).toMatchInlineSnapshot(`
      "<!-- runshape:begin (generated by \`npm run runshape -- readmes\` from the recording of 0123456789ab; edits between these markers are replaced) -->
      ## What's in internal/web

      Mostly **Inbound adapters** code, drawn hexagonal: every zone inferred from what the code did, no runshape.json rules.

      | File | Zone | Classes | Entry points (calls from outside the file), of its functions |
      |---|---|---|---|
      | handler.go | Inbound adapters, Core | Handler, statusRecorder | Handler.ServeHTTP ×5, NewHandler ×4 (of 6) |

      ### Questions this raises

      - handler.go holds more than one kind of code: Inbound adapters (Handler) and Core (statusRecorder). Split it?

      <!-- runshape:end -->
      "
    `);
  });
});

describe("mergeIntoReadme", () => {
  const block = "<!-- runshape:begin -->\nnew\n<!-- runshape:end -->\n";

  test("a new README: a title, a line for a person to fill in, then the guide", () => {
    expect(mergeIntoReadme(null, block, "internal/web")).toEqual({
      status: "created",
      text: "# internal/web\n\n_What this folder is for, in a sentence or two: yours to write; runshape keeps the part below._\n\n<!-- runshape:begin -->\nnew\n<!-- runshape:end -->\n",
    });
  });

  test("a README with the markers: the part between them replaced, the rest kept; the same again is unchanged", () => {
    const existing = "# Web\n\nThe HTTP side of the shop.\n\n<!-- runshape:begin -->\nold\n<!-- runshape:end -->\n\nMore notes.\n";

    const merged = mergeIntoReadme(existing, block, "internal/web");

    expect({ merged, again: mergeIntoReadme(merged.text, block, "internal/web").status }).toEqual({
      merged: { status: "updated", text: "# Web\n\nThe HTTP side of the shop.\n\n<!-- runshape:begin -->\nnew\n<!-- runshape:end -->\n\nMore notes.\n" },
      again: "unchanged",
    });
  });

  test("a README of someone's own, with no markers, is left as it is", () => {
    expect(mergeIntoReadme("# Our web layer\n", block, "internal/web")).toEqual({ status: "skipped", text: "# Our web layer\n" });
  });
});
